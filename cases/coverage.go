package cases

import (
	"fmt"
	"sort"
	"strings"

	casesv1 "github.com/nexteggapp/taxcalcs/cases/v1"
	sourcesv1 "github.com/nexteggapp/taxcalcs/sources/v1"
)

// Loaded is a case and the jurisdiction directory it was read from.
type Loaded struct {
	Jurisdiction string
	Path         string
	Case         *casesv1.TestCase
	Results      []Result
}

// Authoritative reports whether a figure of this provenance was printed by
// the tax agency, and so counts towards coverage.
func Authoritative(p casesv1.Provenance) bool {
	return p == casesv1.Provenance_PROVENANCE_PUBLISHED_EXAMPLE || p == casesv1.Provenance_PROVENANCE_PUBLISHED_TABLE
}

// Suite is a set of tests outside the case files, with the provenance of its
// expected values, for the coverage report.
type Suite struct {
	Name, Where, Size, Provenance string
}

// Suites are the test sets that are not case files. Their sizes are counted
// by hand; update them when a set changes much.
var Suites = []Suite{
	{"Federal return tests", "returns/rules/federal/federal_test.go", "44 test functions", "Hand-worked"},
	{"State return tests", "returns/rules/states/<st>_test.go", "about 170 test functions over 41 states, DC and WA", "Hand-worked"},
	{"California and Oregon to the cent", "returns/rules/states/testdata/go_calculators_2025.json", "44 households", "Frozen regression"},
	{"Estimated tax", "golden/testdata/estimated", "2,436 household-years over 51 jurisdictions", "Frozen regression"},
	{"Go and Rust parity", "golden/testdata/returns, golden/testdata/taxlisp", "417 vectors and the taxlisp IR", "Regenerated from the Go engine"},
}

// Report renders the coverage report: the case files by jurisdiction, each
// form's lines covered by authoritative figures, and the other test sets.
func Report(loaded []Loaded, forms map[string]*Form, catalog []*sourcesv1.Source) string {
	var b strings.Builder
	b.WriteString("# Test coverage\n\n")
	b.WriteString("Generated by `bazel run //cases:cases_test -- -update` from the case files\n")
	b.WriteString("under `cases/`. [docs/testing.md](../docs/testing.md) explains the\n")
	b.WriteString("provenance of an expected figure. Only published examples and published\n")
	b.WriteString("tables count as authoritative.\n\n")

	b.WriteString("## Case files\n\n")
	b.WriteString("| Jurisdiction | Cases | Figures | Authoritative | Other | Passing | Known gaps |\n")
	b.WriteString("|---|---|---|---|---|---|---|\n")
	type row struct{ cases, figures, auth, other, pass, gap int }
	rows := map[string]*row{}
	for _, l := range loaded {
		r := rows[l.Jurisdiction]
		if r == nil {
			r = &row{}
			rows[l.Jurisdiction] = r
		}
		r.cases++
		for _, res := range l.Results {
			r.figures++
			if Authoritative(res.Expected.GetProvenance()) {
				r.auth++
			} else {
				r.other++
			}
			switch res.Outcome {
			case Pass:
				r.pass++
			case Gap:
				r.gap++
			}
		}
	}
	var jurs []string
	for j := range rows {
		jurs = append(jurs, j)
	}
	sort.Strings(jurs)
	for _, j := range jurs {
		r := rows[j]
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %d | %d | %d |\n", strings.ToUpper(j), r.cases, r.figures, r.auth, r.other, r.pass, r.gap)
	}
	if len(jurs) == 0 {
		b.WriteString("| none | 0 | 0 | 0 | 0 | 0 | 0 |\n")
	}

	b.WriteString("\n## Form lines with an authoritative figure\n\n")
	b.WriteString("A line counts when a case checks it with a published figure. The lines\n")
	b.WriteString("are those the source catalog says a form rule implements.\n\n")
	implemented := map[string]map[string]bool{}
	notModeled := map[string]int{}
	for _, src := range catalog {
		for _, a := range src.GetAnchors() {
			if a.GetNotModeled() != "" {
				notModeled[src.GetId()]++
			}
			form, line, ok := strings.Cut(a.GetImplementedBy(), ":")
			if !ok || forms[form] == nil {
				continue
			}
			if implemented[form] == nil {
				implemented[form] = map[string]bool{}
			}
			implemented[form][line] = true
		}
	}
	covered := map[string]map[string]bool{}
	for _, l := range loaded {
		for _, res := range l.Results {
			e := res.Expected
			if !Authoritative(e.GetProvenance()) {
				continue
			}
			if covered[e.GetForm()] == nil {
				covered[e.GetForm()] = map[string]bool{}
			}
			covered[e.GetForm()][e.GetLine()] = true
		}
	}
	var names []string
	for f := range implemented {
		names = append(names, f)
	}
	sort.Strings(names)
	var table strings.Builder
	total, totalCovered := 0, 0
	for _, f := range names {
		var lines []string
		for _, line := range forms[f].Lines {
			if implemented[f][line] {
				lines = append(lines, line)
			}
		}
		var uncovered []string
		for _, line := range lines {
			if !covered[f][line] {
				uncovered = append(uncovered, line)
			}
		}
		total += len(lines)
		totalCovered += len(lines) - len(uncovered)
		fmt.Fprintf(&table, "| `%s` | %d | %d | %s |\n", f, len(lines), len(lines)-len(uncovered), lineList(uncovered))
	}
	fmt.Fprintf(&b, "%d of the %d lines the rules implement, over %d forms, have an authoritative figure.\n\n", totalCovered, total, len(names))
	b.WriteString("| Form | Lines implemented | Covered | Uncovered |\n|---|---|---|---|\n")
	b.WriteString(table.String())

	b.WriteString("\n## Lines the rules leave out\n\n")
	b.WriteString("Anchors the source catalog marks `not_modeled`, by source. A case can\n")
	b.WriteString("assert such a line as a known gap, so it starts passing when the rules\n")
	b.WriteString("grow to cover it.\n\n")
	b.WriteString("| Source | Lines not modelled |\n|---|---|\n")
	var srcs []string
	for s := range notModeled {
		srcs = append(srcs, s)
	}
	sort.Strings(srcs)
	nm := 0
	for _, s := range srcs {
		nm += notModeled[s]
		fmt.Fprintf(&b, "| `%s` | %d |\n", s, notModeled[s])
	}
	fmt.Fprintf(&b, "| Total | %d |\n", nm)

	b.WriteString("\n## Other test sets\n\n")
	b.WriteString("| Set | Where | Size | Expected values |\n|---|---|---|---|\n")
	for _, s := range Suites {
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s |\n", s.Name, s.Where, s.Size, s.Provenance)
	}
	return b.String()
}

func lineList(lines []string) string {
	if len(lines) == 0 {
		return "none"
	}
	return strings.Join(lines, ", ")
}
